"use strict";
// Only dates actually published by the Cabinet Office are imported. No equinox prediction.
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm"),crypto=require("node:crypto");
const PAGE="https://www8.cao.go.jp/chosei/shukujitsu/gaiyou.html";
const CSV="https://www8.cao.go.jp/chosei/shukujitsu/syukujitsu.csv";
const TARGET=path.join(__dirname,"../day-designs/paper-holidays.js"),FIRST_YEAR=2026,MAX_BYTES=2_000_000;
const NAMES=["元日","成人の日","建国記念の日","天皇誕生日","春分の日","昭和の日","憲法記念日","みどりの日","こどもの日","海の日","山の日","敬老の日","秋分の日","スポーツの日","文化の日","勤労感謝の日"];
const iso=(year,month,day)=>`${year}-${String(month).padStart(2,"0")}-${String(day).padStart(2,"0")}`;
const add=(day,n)=>new Date(Date.parse(day+"T00:00:00Z")+n*86400000).toISOString().slice(0,10);
function parseText(text,{expectedYear=new Date().getUTCFullYear()+1}={}){
 if(!Number.isInteger(expectedYear)||expectedYear<FIRST_YEAR||expectedYear>2100)throw new Error("Invalid expected year");
 const rows=text.replace(/^\uFEFF/,"").trimEnd().split(/\r?\n/);
 if(rows.shift()!=="国民の祝日・休日月日,国民の祝日・休日名称")throw new Error("Unexpected Cabinet Office CSV header");
 const published=new Map();let previous="";
 for(const [index,row] of rows.entries()){
  const match=/^(\d{4})\/(\d{1,2})\/(\d{1,2}),([^,"\r\n]{1,40})$/.exec(row);
  if(!match)throw new Error(`Invalid holiday row ${index+2}`);
  const year=Number(match[1]),day=iso(year,Number(match[2]),Number(match[3]));
  if(year<1955||year>2100||!Number.isFinite(Date.parse(day+"T00:00:00Z"))||new Date(day+"T00:00:00Z").toISOString().slice(0,10)!==day)throw new Error(`Invalid holiday date: ${day}`);
  if(day<=previous)throw new Error(`Unsorted or duplicate holiday: ${day}`);
  previous=day;if(year<FIRST_YEAR)continue;
  if(!NAMES.includes(match[4])&&match[4]!=="休日")throw new Error(`Unknown holiday name: ${match[4]}`);
  published.set(day,match[4]);
 }
 const lastYear=Number(previous.slice(0,4));
 if(lastYear<expectedYear)throw new Error(`Official calendar only covers ${lastYear}; ${expectedYear} has not been published. Existing data is unchanged.`);
 for(let year=FIRST_YEAR;year<=lastYear;year++){
  const names=[...published].filter(([day])=>day.startsWith(year+"-")).map(([,name])=>name);
  if(names.length>25||NAMES.some(name=>names.filter(n=>n===name).length!==1))throw new Error(`Incomplete or unexpected holiday calendar for ${year}`);
 }
 const days={};
 const national=d=>published.has(d)&&published.get(d)!=="休日";
 for(const [day,name] of published){
  if(name==="休日")continue;
  if(new Date(day+"T00:00:00Z").getUTCDay()===0){
   let substitute=add(day,1);while(national(substitute))substitute=add(substitute,1);
   if(published.get(substitute)!=="休日")throw new Error(`Missing substitute holiday: ${substitute}`);
  }
  const between=add(day,1);
  if(!national(between)&&national(add(day,2))&&published.get(between)!=="休日")throw new Error(`Missing citizen holiday: ${between}`);
 }
 for(const [day,name] of published){
  if(name!=="休日"){days[day]=name;continue;}
  if(national(add(day,-1))&&national(add(day,1))){days[day]="国民の休日";continue;}
  let prior=add(day,-1),substitute=false;
  while(national(prior)){
   if(new Date(prior+"T00:00:00Z").getUTCDay()===0){substitute=true;break;}
   prior=add(prior,-1);
  }
  if(!substitute)throw new Error(`Cannot classify official holiday: ${day}`);
  days[day]="振替休日";
 }
 return {start:`${FIRST_YEAR}-01-01`,end:`${lastYear}-12-31`,days};
}
function parseCsv(bytes,options){
 if(!bytes.length||bytes.length>MAX_BYTES)throw new Error("Holiday CSV is empty or too large");
 return parseText(new TextDecoder("shift_jis",{fatal:true}).decode(bytes),options);
}
function currentCalendar(filename=TARGET){
 const context={window:{}};vm.runInNewContext(fs.readFileSync(filename,"utf8"),context,{timeout:1000});
 return JSON.parse(JSON.stringify(context.window.PaperHolidays));
}
function render(calendar,checked){
 return `(function(global){\n"use strict";\n// Generated by scripts/update-paper-holidays.cjs from the Cabinet Office CSV.\n// Official published dates only. Source data is processed to label Article 3 holidays.\n// Source: ${PAGE}\n// Checked: ${checked}. Reuse: https://www.cao.go.jp/notice/rule.html\nglobal.PaperHolidays=Object.freeze({\n start:${JSON.stringify(calendar.start)},end:${JSON.stringify(calendar.end)},checked:${JSON.stringify(checked)},\n source:${JSON.stringify(PAGE)},\n csvSource:${JSON.stringify(CSV)},\n days:Object.freeze(${JSON.stringify(calendar.days,null,2)})\n});\n})(window);\n`;
}
function prepareUpdate(bytes,current,{expectedYear,checked=new Date().toISOString().slice(0,10)}={}){
 const calendar=parseCsv(bytes,{expectedYear});
 if(calendar.start!==current.start||calendar.end<current.end)throw new Error("Refusing to remove previously supported calendar years");
 const same=calendar.end===current.end&&JSON.stringify(calendar.days)===JSON.stringify(current.days);
 return {changed:!same,calendar,content:same?null:render(calendar,checked)};
}
function refreshHolidayAsset(html,calendar){
 const version="holidays-"+calendar.end.slice(0,4)+"-"+crypto.createHash("sha256").update(JSON.stringify(calendar.days)).digest("hex").slice(0,12);
 let count=0;
 const result=html.replace(/(\bsrc=["'](?:\.\/)?paper-holidays\.js)(?:\?[^"']*)?(["'])/g,(_,src,quote)=>{count++;return `${src}?v=${version}${quote}`;});
 if(count!==1)throw new Error("Expected exactly one holiday asset in each A HTML entry");
 return result;
}
async function main(){
 const args=process.argv.slice(2);let csvFile=null,expectedYear=new Date().getUTCFullYear()+1;
 for(let i=0;i<args.length;i++){
  if(args[i]==="--csv"&&args[i+1])csvFile=args[++i];
  else if(args[i]==="--expected-year"&&args[i+1])expectedYear=Number(args[++i]);
  else throw new Error("Usage: node scripts/update-paper-holidays.cjs [--csv official.csv] [--expected-year YYYY]");
 }
 let bytes;
 if(csvFile)bytes=fs.readFileSync(csvFile);
 else{
  const response=await fetch(CSV,{redirect:"error",signal:AbortSignal.timeout(30000)});
  if(!response.ok)throw new Error(`Holiday download failed: HTTP ${response.status}`);
  const chunks=[];let size=0;
  for await(const chunk of response.body){size+=chunk.length;if(size>MAX_BYTES)throw new Error("Holiday CSV is too large");chunks.push(chunk);}
  bytes=Buffer.concat(chunks);
 }
 const result=prepareUpdate(bytes,currentCalendar(),{expectedYear});
 if(result.changed){
  // Validate both entries before writing any files. Only the holiday asset cache key changes.
  const entries=["a-paper.html","a-paper-app.html"].map(name=>{
   const file=path.join(path.dirname(TARGET),name);
   return [file,refreshHolidayAsset(fs.readFileSync(file,"utf8"),result.calendar)];
  });
  fs.writeFileSync(TARGET,result.content,"utf8");
  for(const [file,content] of entries)fs.writeFileSync(file,content,"utf8");
 }
 console.log(`${result.changed?"Updated":"Unchanged"}: official holidays ${result.calendar.start} through ${result.calendar.end}`);
}
if(require.main===module)main().catch(error=>{console.error(error.message);process.exitCode=1;});
module.exports={CSV,PAGE,FIRST_YEAR,NAMES,parseText,parseCsv,prepareUpdate,currentCalendar,render,refreshHolidayAsset};
